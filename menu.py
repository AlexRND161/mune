category = input('Что бы вы хотели заказать? напиток, суп или десерт? ')

match category:
    case 'напиток':
        choice = input('У нас есть чай, кофе и сок. Что бы вы хотели? ')
        if choice == 'чай':
            print('Ваш выбор: чай, с вас 200 рублей!')
        elif choice == 'кофе':
            print('Ваш выбор: кофе, с вас 350 рублей!')
        elif choice == 'сок':
            print('Ваш выбор: сок, с вас 450 рублей!')
        else:
            print('К сожалению, такого напитка нет в меню.')

    case 'суп':
        choice = input('У нас есть борщ, щи и суп-пюре. Что бы вы хотели? ')
        if choice == 'борщ':
            print('Ваш выбор: борщ, с вас 700 рублей!')
        elif choice == 'щи':
            print('Ваш выбор: щи, с вас 650 рублей!')
        elif choice == 'суп-пюре':
            print('Ваш выбор: суп-пюре, с вас 800 рублей!')
        else:
            print('К сожалению, такого супа нет в меню.')

    case 'десерт':
        choice = input('У нас есть торт, мороженое и фрукты. Что бы вы хотели? ')
        if choice == 'торт':
            print('Ваш выбор: торт, с вас 600 рублей!')
        elif choice == 'мороженое':
            print('Ваш выбор: мороженое, с вас 300 рублей!')
        elif choice == 'фрукты':
            print('Ваш выбор: фрукты, с вас 400 рублей!')
        else:
            print('К сожалению, такого десерта нет в меню.')

    case _:
        print('Такой категории нет в нашем меню.')
